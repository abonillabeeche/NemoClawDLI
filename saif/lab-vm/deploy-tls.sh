#!/usr/bin/env bash
# Serve the lab VM over HTTPS with the lab wildcard cert. The course signs its OpenClaw gateway
# login with WebCrypto Ed25519, which browsers only expose in secure contexts (HTTPS or localhost):
# over plain http://<ip> the gateway socket closes before connect.
#   saif/lab-vm/deploy-tls.sh [labadmin@10.0.0.164]      # rerun after each cert renewal
# Needs a DNS name under the cert, e.g.  cli53 rrcreate 5glinux.com 'saif-lab 300 A 10.0.0.164'
set -euo pipefail
VM="${1:-labadmin@10.0.0.164}"
CERT_DIR="${CERT_DIR:-$HOME/.acme.sh/*.5glinux.com_ecc}"
FULLCHAIN="$CERT_DIR/fullchain.cer"; KEY="$CERT_DIR/*.5glinux.com.key"
[ -r "$FULLCHAIN" ] && [ -r "$KEY" ] || { echo "cert files not found in $CERT_DIR" >&2; exit 1; }

ssh "$VM" 'sudo install -d -m 0750 -o root -g www-data /etc/nginx/saif-tls && sudo tee /etc/nginx/saif-tls/fullchain.pem >/dev/null' < "$FULLCHAIN"
ssh "$VM" 'sudo install -m 0640 -o root -g www-data /dev/stdin /etc/nginx/saif-tls/privkey.pem' < "$KEY"

# HTTPS twin of the VM's live HTTP site (same routes, TLS listener, no duplicate map block).
# Built on the VM from /etc/nginx/sites-available/saif so templated values match the running config.
ssh "$VM" 'sudo python3 -I - <<"PY"
src = open("/etc/nginx/sites-available/saif").read()
src = "\n".join(l for l in src.splitlines() if not l.startswith("map $http_upgrade"))
src = src.replace("    listen 80 default_server;",
    "    listen 443 ssl http2 default_server;\n"  # nginx 1.24 (Ubuntu 24.04): no standalone http2 on;
    "    ssl_certificate /etc/nginx/saif-tls/fullchain.pem;\n"
    "    ssl_certificate_key /etc/nginx/saif-tls/privkey.pem;")
open("/etc/nginx/sites-available/saif-tls", "w").write("# HTTPS twin generated by saif/lab-vm/deploy-tls.sh\n" + src)
PY'
ssh "$VM" 'sudo ln -sf /etc/nginx/sites-available/saif-tls /etc/nginx/sites-enabled/saif-tls && sudo nginx -t && sudo systemctl reload nginx && echo "HTTPS enabled"'
